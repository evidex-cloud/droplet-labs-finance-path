如果公司的股价像一辆平稳行驶的公交车，彩票几乎不值钱，没人愿意零利息借钱。如果股价像一辆过山车——比特币上面再加杠杆——这张彩票就很值钱，大家抢着借。

套利基金的玩法是：买下借条和彩票，然后**在过山车上反向坐一个小座位**（卖空一部分股票）。过山车每一次冲上去，它就多卖一点；每一次冲下来，它就买回一点。只要过山车晃得够猛，这一上一下的差价就是它的收入——它根本不关心过山车最后停在山顶还是谷底。

而借条上还写着一行小字：“某年某月某日，你有权要求我先还钱。”——那一天，就是这张借条真正的到期日。过山车那时停在谷底，公司就得准备好现金。
