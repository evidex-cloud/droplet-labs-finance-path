坏账出现后谁买单？视协议而定：协议金库、专门的保险/安全模块（质押协议代币的人承担首损），最后才是存款人按比例分摊。**存款人以为自己在赚“无风险”的稳定币利息，实际上是这座抵押品大厦最底层的承担者**。

